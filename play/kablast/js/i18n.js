  function setup(id) {
    lang = resolve(id) || 'en'; tag = LANGS.find(l => l.id === lang).tag;
    try { plural = new Intl.PluralRules(tag); } catch (e) { plural = null; }
    try { numFmt = new Intl.NumberFormat(tag, { maximumFractionDigits: 0 }); } catch (e) { numFmt = null; }
    if (typeof document !== 'undefined') { document.documentElement.lang = tag; document.documentElement.classList.toggle('cyr', lang === 'ru'); }
  }
  setup('en');

  // t('key', { n: 3 }) — plural entries pick their form from n (or v); function entries get the vars object
  function t(key, vars) {
    let s = D[lang][key]; if (s === undefined) s = en[key]; if (s === undefined) return key;
    vars = vars || {};
    if (typeof s === 'function') return s(vars);
    if (typeof s === 'object') {
      const n = vars.n !== undefined ? vars.n : vars.v;
      const form = plural && typeof n === 'number' ? plural.select(n) : 'other';
      s = s[form] || s.other;
    }
    return s.replace(/\{(\w+)\}/g, (m, k) => {
      const x = vars[k]; if (x === undefined) return m;
      return typeof x === 'number' ? num(x) : x;
    });
  }
  function num(n) { n = Math.floor(n); return numFmt ? numFmt.format(n) : String(n); }
  const upper = s => String(s).toLocaleUpperCase(tag);
